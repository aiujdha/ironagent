import type { IronAgentApp } from "./app.ts";
import { loadDebug } from "./controllers/debug.ts";
import { loadLogs } from "./controllers/logs.ts";
import { loadNodes } from "./controllers/nodes.ts";

type PollingHost = {
  nodesPollInterval: number | null;
  logsPollInterval: number | null;
  debugPollInterval: number | null;
  workspaceFilesPollInterval: number | null;
  tab: string;
  sessionKey?: string;
  workspaceFilesLoading?: boolean;
};

export const NODES_POLL_INTERVAL_MS = 30000;
export const WORKSPACE_FILES_POLL_INTERVAL_MS = 0;

export function startNodesPolling(host: PollingHost) {
  if (host.nodesPollInterval != null) {
    return;
  }
  host.nodesPollInterval = window.setInterval(
    () => void loadNodes(host as unknown as IronAgentApp, { quiet: true }),
    NODES_POLL_INTERVAL_MS,
  );
}

export function stopNodesPolling(host: PollingHost) {
  if (host.nodesPollInterval == null) {
    return;
  }
  clearInterval(host.nodesPollInterval);
  host.nodesPollInterval = null;
}

export function startLogsPolling(host: PollingHost) {
  if (host.logsPollInterval != null) {
    return;
  }
  host.logsPollInterval = window.setInterval(() => {
    if (host.tab !== "logs") {
      return;
    }
    void loadLogs(host as unknown as IronAgentApp, { quiet: true });
  }, 2000);
}

export function stopLogsPolling(host: PollingHost) {
  if (host.logsPollInterval == null) {
    return;
  }
  clearInterval(host.logsPollInterval);
  host.logsPollInterval = null;
}

export function startDebugPolling(host: PollingHost) {
  if (host.debugPollInterval != null) {
    return;
  }
  host.debugPollInterval = window.setInterval(() => {
    if (host.tab !== "debug") {
      return;
    }
    void loadDebug(host as unknown as IronAgentApp);
  }, 3000);
}

export function stopDebugPolling(host: PollingHost) {
  if (host.debugPollInterval == null) {
    return;
  }
  clearInterval(host.debugPollInterval);
  host.debugPollInterval = null;
}

export function startWorkspaceFilesPolling(host: PollingHost) {
  host.workspaceFilesPollInterval = null;
}

export function stopWorkspaceFilesPolling(host: PollingHost) {
  if (host.workspaceFilesPollInterval == null) {
    return;
  }
  clearInterval(host.workspaceFilesPollInterval);
  host.workspaceFilesPollInterval = null;
}
