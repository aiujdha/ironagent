#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import zipfile
from io import BytesIO


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create minimal Word, Excel, and matching PDF artifacts without external dependencies."
    )
    parser.add_argument("--out-dir", required=True, help="Directory to write outputs into.")
    parser.add_argument("--title", default="Office Smoke", help="Word title and PDF title text.")
    parser.add_argument(
        "--body",
        default="Generated by IronAgent inside the container.",
        help="Body paragraph for the Word document and word PDF.",
    )
    parser.add_argument("--word-docx", default="agent-word.docx", help="Word output filename.")
    parser.add_argument("--word-pdf", default="agent-word.pdf", help="Word PDF output filename.")
    parser.add_argument("--sheet-xlsx", default="agent-sheet.xlsx", help="Excel output filename.")
    parser.add_argument("--sheet-pdf", default="agent-sheet.pdf", help="Excel PDF output filename.")
    parser.add_argument(
        "--manifest-json",
        help="Optional JSON file path to write a machine-readable output summary.",
    )
    parser.add_argument(
        "--stdout-json",
        action="store_true",
        help="Print a JSON summary to stdout instead of tab-separated filename rows.",
    )
    parser.add_argument("--sheet-name", default="Summary", help="Worksheet name.")
    parser.add_argument(
        "--headers",
        default="Item,Status",
        help="Comma-separated Excel header row.",
    )
    parser.add_argument(
        "--row",
        action="append",
        default=[],
        help="Comma-separated Excel row. Repeat to add multiple rows.",
    )
    return parser.parse_args()


def ensure_parent(path: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)


def split_csv_row(value: str) -> list[str]:
    return [part.strip() for part in value.split(",")]


def build_word_docx(path: str, title: str, body: str) -> None:
    content_types = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>
"""

    rels = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>
"""

    def paragraph(text: str) -> str:
        return f"<w:p><w:r><w:t>{escape_xml(text)}</w:t></w:r></w:p>"

    document_xml = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:body>
    {paragraph(title)}
    {paragraph(body)}
  </w:body>
</w:document>
"""

    ensure_parent(path)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("[Content_Types].xml", content_types)
        zf.writestr("_rels/.rels", rels)
        zf.writestr("word/document.xml", document_xml)


def escape_xml(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&apos;")
    )


def build_output_summary(
    out_dir: str,
    word_docx: str,
    word_pdf: str,
    sheet_xlsx: str,
    sheet_pdf: str,
) -> dict[str, object]:
    normalized_out_dir = os.path.abspath(out_dir)
    outputs = [word_docx, word_pdf, sheet_xlsx, sheet_pdf]
    files: list[dict[str, object]] = []
    for output in outputs:
        files.append(
            {
                "name": os.path.basename(output),
                "path": os.path.abspath(output),
                "sizeBytes": os.path.getsize(output),
            }
        )

    return {
        "outDir": normalized_out_dir,
        "files": files,
        "word": {
            "docx": files[0],
            "pdf": files[1],
        },
        "sheet": {
            "xlsx": files[2],
            "pdf": files[3],
        },
    }


def build_min_pdf(path: str, lines: list[str]) -> None:
    buffer = BytesIO()

    def add_object(obj_str: str, offsets: list[int]) -> None:
        offsets.append(buffer.tell())
        buffer.write((obj_str + "\n").encode("ascii"))

    buffer.write(b"%PDF-1.4\n")

    offsets: list[int] = []
    add_object("1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj", offsets)
    add_object("2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj", offsets)
    add_object(
        "3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        "/Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj",
        offsets,
    )

    text_lines = ["BT /F1 16 Tf 72 730 Td"]
    first = True
    for line in lines:
        safe = line.replace("(", "[").replace(")", "]")
        if first:
            text_lines.append(f"({safe}) Tj")
            first = False
        else:
            text_lines.append("T*")
            text_lines.append(f"({safe}) Tj")
    text_lines.append("ET")

    stream_data = ("\n".join(text_lines) + "\n").encode("ascii")
    stream_header = f"4 0 obj << /Length {len(stream_data)} >> stream\n".encode("ascii")
    stream_footer = b"endstream\nendobj\n"
    contents_offset = buffer.tell()
    buffer.write(stream_header)
    buffer.write(stream_data)
    buffer.write(stream_footer)

    add_object("5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj", offsets)

    xref_offset = buffer.tell()
    buffer.write(b"xref\n0 6\n")
    buffer.write(b"0000000000 65535 f \n")
    page_offsets = [offsets[0], offsets[1], offsets[2], contents_offset, offsets[3]]
    for offset in page_offsets:
        buffer.write(f"{offset:010d} 00000 n \n".encode("ascii"))

    buffer.write(b"trailer << /Size 6 /Root 1 0 R >>\n")
    buffer.write(b"startxref\n")
    buffer.write(str(xref_offset).encode("ascii"))
    buffer.write(b"\n%%EOF\n")

    ensure_parent(path)
    with open(path, "wb") as f:
        f.write(buffer.getvalue())


def build_excel_xlsx(path: str, sheet_name: str, headers: list[str], rows: list[list[str]]) -> None:
    shared_strings_values = headers[:]
    for row in rows:
        for value in row:
            if value not in shared_strings_values:
                shared_strings_values.append(value)

    shared_strings_index = {value: idx for idx, value in enumerate(shared_strings_values)}

    def make_cell(ref: str, value: str) -> str:
        return f'<c r="{ref}" t="s"><v>{shared_strings_index[value]}</v></c>'

    content_types = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
  <Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
  <Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>
  <Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>
  <Override PartName="/docProps/app.xml" ContentType="application/vnd.openxmlformats-officedocument.extended-properties+xml"/>
  <Override PartName="/xl/sharedStrings.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sharedStrings+xml"/>
</Types>
"""

    rels_root = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
  <Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="docProps/core.xml"/>
  <Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/extended-properties" Target="docProps/app.xml"/>
</Relationships>
"""

    workbook = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheets>
    <sheet name="{escape_xml(sheet_name)}" sheetId="1" r:id="rId1"/>
  </sheets>
</workbook>
"""

    workbook_rels = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
  <Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
  <Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/sharedStrings" Target="sharedStrings.xml"/>
</Relationships>
"""

    styles = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <fonts count="1"><font><sz val="11"/><name val="Calibri"/></font></fonts>
  <fills count="1"><fill><patternFill patternType="none"/></fill></fills>
  <borders count="1"><border/></borders>
  <cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>
  <cellXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/></cellXfs>
</styleSheet>
"""

    row_xml_parts: list[str] = []
    all_rows = [headers] + rows
    for row_idx, row in enumerate(all_rows, start=1):
        cell_parts = []
        for col_idx, value in enumerate(row, start=1):
            col_letter = chr(ord("A") + col_idx - 1)
            cell_parts.append(make_cell(f"{col_letter}{row_idx}", value))
        row_xml_parts.append(f'<row r="{row_idx}">{"".join(cell_parts)}</row>')

    sheet = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheetData>
    {"".join(row_xml_parts)}
  </sheetData>
</worksheet>
"""

    shared_strings = (
        """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n"""
        f'<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" count="{len(shared_strings_values)}" uniqueCount="{len(shared_strings_values)}">'
        + "".join(f"<si><t>{escape_xml(value)}</t></si>" for value in shared_strings_values)
        + "</sst>\n"
    )

    core = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/">
  <dc:title>Office Smoke</dc:title>
</cp:coreProperties>
"""

    app = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/extended-properties" xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes">
  <Application>IronAgent</Application>
</Properties>
"""

    ensure_parent(path)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("[Content_Types].xml", content_types)
        zf.writestr("_rels/.rels", rels_root)
        zf.writestr("xl/workbook.xml", workbook)
        zf.writestr("xl/_rels/workbook.xml.rels", workbook_rels)
        zf.writestr("xl/styles.xml", styles)
        zf.writestr("xl/worksheets/sheet1.xml", sheet)
        zf.writestr("xl/sharedStrings.xml", shared_strings)
        zf.writestr("docProps/core.xml", core)
        zf.writestr("docProps/app.xml", app)


def main() -> None:
    args = parse_args()
    os.makedirs(args.out_dir, exist_ok=True)

    headers = split_csv_row(args.headers)
    rows = [split_csv_row(row) for row in args.row] or [["Office Smoke", "Done"]]

    word_docx = os.path.join(args.out_dir, args.word_docx)
    word_pdf = os.path.join(args.out_dir, args.word_pdf)
    sheet_xlsx = os.path.join(args.out_dir, args.sheet_xlsx)
    sheet_pdf = os.path.join(args.out_dir, args.sheet_pdf)

    build_word_docx(word_docx, args.title, args.body)
    build_min_pdf(word_pdf, [args.title, args.body])
    build_excel_xlsx(sheet_xlsx, args.sheet_name, headers, rows)

    pdf_rows = ["    ".join(headers)]
    for row in rows:
        pdf_rows.append("    ".join(row))
    build_min_pdf(sheet_pdf, pdf_rows)

    outputs = [word_docx, word_pdf, sheet_xlsx, sheet_pdf]
    for output in outputs:
        if not os.path.exists(output):
            raise SystemExit(f"missing expected file: {output}")

    summary = build_output_summary(args.out_dir, word_docx, word_pdf, sheet_xlsx, sheet_pdf)
    if args.manifest_json:
        ensure_parent(args.manifest_json)
        with open(args.manifest_json, "w", encoding="utf-8") as handle:
            json.dump(summary, handle, indent=2)
            handle.write("\n")

    if args.stdout_json:
        print(json.dumps(summary, indent=2))
        return

    for output in outputs:
        print(f"{os.path.basename(output)}\t{os.path.getsize(output)}")


if __name__ == "__main__":
    main()
